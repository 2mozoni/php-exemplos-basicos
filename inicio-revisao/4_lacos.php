<?php

//  laço for para a tabuada do 8
for($i = 1; $i <= 10; $i++) {
    echo "8 x $i =" . (8 * $i) . "\n";
}

// While - (enquanto contagem regressiva)
 echo "<br>";
$n = 5;
while ($n > 0) {
    echo $n. "<br>";
    $n--;
}
echo "<br>";

// Do while - (faça enquanto) executa ao menos 1 vez
$x = 10;
do {
    echo "x vale: $x "
    $x++;
} while ($x < 10);


